/** Проверка поиска по базе знаний: npm run kb -- "вопрос" ["вопрос" ...]. Без аргументов — набор типовых вопросов. */
import { KbIndex } from '../packages/kb/src/index.js';
const kb = KbIndex.fromDir('kb');
console.log('chunks', kb.chunks.length);
const qs = process.argv.slice(2).length ? process.argv.slice(2) : [
  'Сколько правил можно настроить на одном Синониксе?',
  'Зачем ещё нужен межсетевой экран, если уже стоит Синоникс?',
  'Хотим передавать обновления в закрытую сеть и проверять их встроенным антивирусом Синоникса',
  'Можно ли подключить флешку к Узлу В?',
  'Какая скорость у устройства?',
  'Есть ли сертификат ФСТЭК?',
  'Как остановить обмен в экстренной ситуации?',
  'Чем Синоникс отличается от диода данных?',
  'Можно ли открыть доступ ко всей подсети?',
  'Поддерживает ли Modbus однонаправленный режим?',
];
for (const q of qs) {
  console.log('\n## ' + q);
  for (const h of kb.search(q, 3)) console.log(`  ${h.score}  ${h.chunk.id}  ${h.chunk.section}\n      > ${h.excerpt.join('\n      > ').slice(0, 300)}`);
}
