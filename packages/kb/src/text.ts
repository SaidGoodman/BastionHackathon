/**
 * Токенизация русского текста для поиска по ключевым словам: нижний регистр, ё→е,
 * лёгкое отсечение окончаний (без словаря), стоп-слова и синонимы предметной области.
 */

const STOP = new Set(
  (
    'и в во не что он на я с со как а то все она так его но да ты к у же вы за бы по только ее мне было вот от меня еще нет о из ему ' +
    'теперь когда даже ну ли если уже или ни быть был него до вас нибудь опять уж вам ведь там потом себя ничего ей может они тут где ' +
    'есть надо ней для мы тебя их чем была сам чтоб без будто чего раз тоже себе под будет ж тогда кто этот того потому этого какой ' +
    'совсем ним здесь этом один почти мой тем чтобы нее сейчас были куда зачем всех никогда можно при наконец об хоть после над больше ' +
    'тот через эти нас про всего них какая много разве эту моя впрочем хорошо свою этой перед иногда лучше чуть том такой им более ' +
    'всегда конечно всю между это сколько почему какие каких какое каким стоит нужен нужна нужно нужны также либо например ' +
    'синоникс синоникса синониксе синониксом синониксу скио пак'
  ).split(/\s+/),
);

// Окончания по убыванию длины; отсекается одно, если остаётся основа не короче 4 букв.
const ENDINGS = [
  'иями', 'ями', 'ами', 'ого', 'его', 'ому', 'ему', 'ыми', 'ими', 'иях', 'ией',
  'ая', 'яя', 'ую', 'юю', 'ой', 'ей', 'ий', 'ый', 'ое', 'ее', 'ые', 'ие', 'ых', 'их', 'ым', 'им', 'ом', 'ем',
  'ия', 'ья', 'ье', 'ии', 'ов', 'ев', 'ям', 'ам', 'ах', 'ях', 'ою', 'ею', 'ть', 'ет', 'ют', 'ут', 'ит', 'ят',
  'ы', 'и', 'а', 'я', 'о', 'е', 'у', 'ю', 'ь', 'й',
];

export function stem(w: string): string {
  if (!/[а-я]/.test(w) || w.length <= 4) return w;
  for (const e of ENDINGS) if (w.endsWith(e) && w.length - e.length >= 4) return w.slice(0, -e.length);
  return w;
}

export function words(text: string): string[] {
  return text
    .toLowerCase()
    .replace(/ё/g, 'е')
    // «Узел А» / «Узел В»: буквы А и В — стоп-слова, поэтому склеиваются с узлом в отдельный токен.
    .replace(/(узел|узла|узлу|узлом|узле)[\s-]+([ав])(?![а-я])/g, (_m: string, _u: string, l: string) => (l === 'а' ? ' nodea ' : ' nodeb '))
    .split(/[^a-zа-я0-9]+/)
    .filter((w) => w && !STOP.has(w));
}

/** Сокращения раскрываются и в документах, и в запросе: «МЭ» в методике = «межсетевой экран» в вопросе. */
const ABBR: Record<string, string[]> = {
  мэ: ['межсетев', 'экран'],
  флешк: ['usb', 'носител'],
  флешек: ['usb', 'носител'],
};

export function tokenize(text: string): string[] {
  const out: string[] = [];
  for (const w of words(text)) {
    const s = stem(w);
    out.push(s);
    const a = ABBR[s];
    if (a) out.push(...a);
  }
  return out;
}

/**
 * Синонимы и сокращения, которыми пользователь называет то же, что в базе знаний.
 * Применяются только к запросу: слово слева добавляет основы справа с половинным весом.
 */
const SYNONYMS: [string, string][] = [
  ['фаервол', 'межсетевой экран'],
  ['файрвол', 'межсетевой экран'],
  ['firewall', 'межсетевой экран'],
  ['межсетевой', 'ngfw'],
  ['ngfw', 'межсетевой экран'],
  ['ав', 'антивирус'],
  ['антивирус', 'icap'],
  ['usb', 'носитель'],
  ['лимит', 'ограничение'],
  ['максимум', 'ограничение'],
  ['максимальное', 'ограничение'],
  ['диод', 'data diode'],
  ['маршрутизация', 'маршрут подсеть'],
  ['подсеть', 'маршрутизирует диапазон'],
  ['сертификат', 'фстэк'],
  ['siem', 'журнал событий'],
  ['логи', 'журнал'],
  ['журналы', 'siem'],
  ['остановить', 'ключ остановка'],
  ['отключить', 'ключ остановка'],
  ['песочница', 'sandbox icap'],
  ['dlp', 'icap'],
  ['подпись', 'целостность'],
  ['скорость', 'гбит'],
  ['пропускная', 'гбит'],
];
const SYN = new Map<string, string[]>();
for (const [k, v] of SYNONYMS) {
  const key = stem(k);
  SYN.set(key, [...(SYN.get(key) ?? []), ...tokenize(v)]);
}

/** Токены запроса с весами: слова пользователя — 1, добавленные синонимы — 0,5. */
export function queryTerms(q: string): Map<string, number> {
  const out = new Map<string, number>();
  for (const t of tokenize(q)) {
    out.set(t, 1);
    for (const s of SYN.get(t) ?? []) if (!out.has(s)) out.set(s, 0.5);
  }
  return out;
}
